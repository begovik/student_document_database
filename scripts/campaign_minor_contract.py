"""Планування кампанії збору: «Укладення і виконання договору за участі
неповнолітньої особи» (договірне право, цивільне право України).

Тільки українські джерела (рішення власника 02.10.2026). Канал — OpenAlex.

Чому OpenAlex, а не DDGS
------------------------
Живий тест 02.10.2026 через DDGSSearchChannel:
    «ЦК України стаття 42 неповнолітній згода filetype:pdf» → 10 кандидатів,
    усі — сторонні сайти (bokephot.net, summerplaceal.com);
    «здатність до укладення договору неповнолітнім» → 0.
OpenAlex з тими самими темами:
    «неповнолітній договір цивільний кодекс» → 67 робіт, у перших п'яти —
    «ОСОБЛИВОСТІ НАДАННЯ НЕПОВНОЛІТНІЙ ОСОБІ ПОВНОЇ ЦИВІЛЬНОЇ ДІЄЗДАТНОСТІ»,
    «Правовий статус осіб віком до 18 років…», «Особливості правового статусу
    дитини у Цивільному кодексі України» — усі з робочим PDF.

Чому без institutions.country_code:UA
-------------------------------------
Продакшн-ітератор openalex його використовує, і це звужує вибірку у ~8 разів
(«неповнолітній договір цивільний кодекс»: 67 → 8). Українські правові журнали
не індексуються з UA-інституцією в OpenAlex. Тому тут лише language:uk.

Чому без DDGS-запитів
---------------------
`harvester add-queries` не придатний: його шаблони жорстко заточені під
виробництво («конструювання», «пошиття пальта», «маршрутна карта»), тож для
правової теми дав би «проєктування укладення договору за участі
неповнолітньої особи filetype:pdf». Плюс сам DDGS-канал дав нерелевантну
видачу. Запити нижче — виміряні, з реальними розмірами вибірки.

Кожне число в коментарі — це meta.count, виміряний через
scripts/campaign_probe_counts.py, а не оцінка.

Запуск:
    venv/bin/python scripts/campaign_minor_contract.py --dry-run
    venv/bin/python scripts/campaign_minor_contract.py --apply
"""

import argparse
import asyncio
from datetime import UTC, datetime

from harvester.core.scheduler import Scheduler
from harvester.db.failover import build_database

# Кампанія обслуговується першою: pick_task сортує priority DESC.
CAMPAIGN_PRIORITY = 100
PER_PAGE = 100

# Фільтр: тільки українська мова + відкритий доступ (потрібен PDF).
# language:uk відсікає російські праці, які pipeline і так відкидав би як
# filtered_ru — краще не витрачати на них квоту завантаження й верифікації.
BASE_FILTER = {"language": "uk", "is_oa": True}

# ── Напрями Н1..Н5 картки + супровідні ───────────────────────────────────
# (search, виміряний meta.count станом на 02.10.2026)
QUERIES: list[tuple[str, int]] = [
    # Н1. Правовий статус неповнолітньої особи
    ("неповнолітній договір цивільний кодекс", 67),
    ("дієздатність неповнолітньої особи", 112),
    ("цивільна дієздатність неповнолітнього", 65),
    ("законне представництво неповнолітньої особи", 20),
    ("цивільна правосуб'єктність неповнолітніх", 49),
    ("неповнолітній суб'єкт цивільного права", 105),
    ("опіка піклування майно дитини розпорядження", 46),
    # Н2. Свобода договору та її межі
    ("свобода договору межі добросовісність сторін", 70),
    ("захист слабшої сторони договір цивільне право", 19),
    # Н3. Укладення договору (центральний напрям)
    ("укладення договору неповнолітнім", 128),
    ("договір укладений неповнолітнім згода батьків", 33),
    ("недійсність договору неповнолітній", 25),
    ("зобов'язальне право неповнолітніх", 37),
    # Н4. Виконання договору
    ("виконання договору неповнолітнім", 185),
    ("припинення договору неповнолітнім", 139),
    ("майно дитини розпорядження договір", 270),
    ("захист прав дитини майно договір", 358),
    ("припинення договору досягненням 18 років", 434),
    # Н5. Правові наслідки порушення
    ("добросовісний набувач майно дитини", 5),
    # Дисертації та автореферати (картка: 1-3 позиції)
    ("автореферат дисертації цивільне право договір", 15),
    ("цивільний кодекс України зобов'язальне право неповнолітній", 6),
    # Дисциплінарний контекст: підручники й монографії з договірного права.
    # Картка ставить їх у фільтр відкидання, але «написання курсової за
    # методичками» саме на них спирається — тому збираємо з позначкою
    # і відсів робимо вручну на звіті (тип doc_type), а не в пошуку.
    ("цивільне право України договірне право монографія", 100),
    ("договірне право України підручник", 213),
    ("цивільне право України підручник договірне право", 83),
    # Методичні матеріали — окремий тип, у картці не зарахований, але потрібний
    ("цивільне право договірне право методичні вказівки", 21),
    ("цивільне право України договірні відносини практикум", 10),
]


def build_tasks() -> list[dict]:
    """Побудувати payload-и задач api_iter для кампанії."""
    return [
        {
            "filters": {**BASE_FILTER, "search": search},
            "cursor": "*",
            "per_page": PER_PAGE,
            # Позначка для журналу: звідки взято цю задачу. Не впливає на
            # запит до API — потрібна, щоб за потім відрізнити кампанію від
            # рутинного курсорного сканування в общем журналі.
            "campaign": "minor_contract",
            "priority": CAMPAIGN_PRIORITY,
        }
        for search, _ in QUERIES
    ]


async def main() -> int:
    ap = argparse.ArgumentParser(description="Кампанія: договір за участі неповнолітнього")
    ap.add_argument("--apply", action="store_true", help="внести задачі (без — лише показати)")
    ap.add_argument("--limit", type=int, default=0, help="внести лише перші N (0 = усі)")
    args = ap.parse_args()

    tasks = build_tasks()
    if args.limit:
        tasks = tasks[: args.limit]

    total_expected = sum(c for _, c in QUERIES[: len(tasks)])
    print(f"Задач: {len(tasks)}, сумарно очікується ~{total_expected} робіт OpenAlex")
    print(f"Пріоритет: {CAMPAIGN_PRIORITY}, сторінка: {PER_PAGE}\n")
    for search, count in QUERIES[: len(tasks)]:
        print(f"  {count:>5}  {search}")

    if not args.apply:
        print("\n[DRY-RUN] Нічого не внесено. Додайте --apply.")
        return 0

    db = build_database()
    await db.initialize()
    scheduler = Scheduler(db)
    inserted = deduped = 0
    for task in tasks:
        # Пріоритет живе і в payload, і в колонці tasks.priority: pick_task
        # сортує саме за колонкою, а payload-пріоритет переноситься в
        # наступну сторінку курсору (див. workers._schedule_next_openalex_page).
        task_id = await scheduler.schedule_task(
            "api_iter", task, priority=CAMPAIGN_PRIORITY
        )
        if task_id:
            inserted += 1
        else:
            deduped += 1

    print(f"\nВнесено: {inserted}, дублікатів (UNIQUE payload_hash): {deduped}")
    print(f"Час: {datetime.now(UTC).replace(tzinfo=None).isoformat()} — це ж значення")
    print("verifier.focus_first_seen_after, щоб рахувати лише дожлені нове.")
    await db.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
