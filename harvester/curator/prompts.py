"""LLM-промпти для кураторських рішень."""

# === Промпти для відбору документів (етап 1) ===

# Строгий промпт (strict)
PROMPT_SELECT_DOCUMENTS_STRICT = """\
Ти — експертний куратор науково-освітньої бібліотеки. Твоя задача — відібрати лише повноцінні, цілісні, логічно завершені джерела для теми "{topic}".

КРИТЕРІЇ ТА СКІЛИ ВІДБОРУ ДЖЕРЕЛ:
1. КРИТЕРІЙ ЦІЛІСНОСТІ ТА СТРУКТУРИ (ЖОРСТКО):
   - Документ має бути ПОВНОЦІННИМ джерелом, яке висвітлює тему повністю або її значну частину.
   - ПРИЙНЯТНІ ДЖЕРЕЛА: цілісні наукові та прикладні статті, монографії, навчальні посібники/підручники, технічні описи та звіти, тези/есе/дипломні роботи з висвітленою структурою (титул, вступ/мета, розділи/підрозділи, висновки, список джерел).
   - НЕПРИЙНЯТНІ ДЖЕРЕЛА (СУВОРО ВІДКИДАТИ): 1-2 сторінкові тези, обрізані анотації, рекламні буклети, уривки без контексту, незакінчені чернетки, фрагментарні презентації.

2. ЯКІСТЬ ТА РЕЛЕВАНТНІСТЬ МЕТАДАНИХ:
   - Обов'язкова наявність осмисленого заголовка та авторів.
   - ВІДКИДАЙ назви: "Microsoft Word - ...", "Unknown", "Untitled", файлові розширення (.doc, .pdf) в назві, сміттєві символи.
   - ВІДКИДАЙ авторів: "USER", "Admin", "1", "Unknown", або неповні ініціали без прізвищ.

3. БАЛАНС ТА РІЗНОМАНІТНІСТЬ:
   - Перевага віддається сучасним джерелам з високим topic_score.
   - Уникай дублювання однакових робіт одних і тих самих авторів.

КАНДИДАТИ ({count} шт.):
"""

# М'який промпт (softier)
PROMPT_SELECT_DOCUMENTS_SOFTIER = """\
Ти — куратор наукової бібліотеки. Твоя задача — відібрати найкращі документи для теми "{topic}".

КРИТЕРІЇ ВІДБОРУ:
1. Документи мають бути пов'язані з темою та містити корисну інформацію.
2. Перевага — повні статті, описи, навчальні матеріали з чіткою структурою.
3. Документи можуть бути короткими (від 1 сторінки), якщо вони якісні та релевантні.
4. Уникай дублювання однакових робіт одних і тих самих авторів.

КАНДИДАТИ ({count} шт.):
"""

# Форматування одного кандидата (спільне для обох профілів)
CANDIDATE_LINE = """\
  {id}. {title} |автори: {authors} |рік: {year} |стор: {page_count} |тип: {doc_type} |школа теми: {topic_score:.2f}
"""

# Кінець промпта для відбору (спільне для обох профілів)
PROMPT_SELECT_END = """\
ЗАВДАННЯ:
1. Визнач оптимальну кількість документів (10-50) для якісного покриття теми.
2. Обери найкращі документи за релевантністю, якістю та різноманітністю.
3. Поверни список ID обраних документів.

ВІДПОВІДЬ (тільки JSON, без пояснень):
{"suggested_count": N, "selected_ids": [157, 1234, ...], "reasoning": "коротка причина"}
"""


def get_selection_prompt(completeness_level: str = "basic") -> str:
    """Отримати промпт для відбору документів залежно від рівня строгості."""
    if completeness_level == "strict":
        return PROMPT_SELECT_DOCUMENTS_STRICT
    else:
        return PROMPT_SELECT_DOCUMENTS_SOFTIER


